#!/usr/bin/env python3
"""Generate one Java enum constant per sheet row. Run preflight first."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "mod/src/main/java/gg/riderscraft/gen")
os.makedirs(OUT, exist_ok=True)
def sheet(n): return json.load(open(os.path.join(ROOT, "sheets", n + ".json")))
def j(v):
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return f"{float(v)}f" if isinstance(v, float) else str(v)
    return json.dumps(v)
HEAD = "// GENERATED by tools/codegen.py from sheets/{0}.json - edit the sheet, not this file.\npackage gg.riderscraft.gen;\n\n"

g = sheet("gear")
lines = []
for r in g["rows"]:
    lines.append(f'    {r["id"].upper()}({j(r["name"])}, {j(r["sport"])}, Physics.{r["physics"].upper()}, {r["wheelSlot"]}, '
                 f'{float(r["maxSpeed"])}f, {float(r["pedalAccel"])}f, {float(r["pedalTopSpeed"])}f, {float(r["turnRate"])}f, {float(r["slopeGain"])}f, {float(r["friction"])}f, '
                 f'{j(r["canClimb"])}, {float(r["stepHeight"])}f, {float(r["jumpBoost"])}f, {float(r["glideLift"])}f, {float(r["glideDive"])}f, '
                 f'{float(r["glideClimb"])}f, {float(r["glideDrag"])}f, {float(r["boostAccel"])}f, {r["boostFuelTicks"]}, {float(r["fuelRegen"])}f, '
                 f'{j(r["rrModel"])}, {j(r["rrSound"])}, {j(r["fallbackShape"])})')
open(os.path.join(OUT, "Gear.java"), "w").write(HEAD.format("gear") + """public enum Gear {
""" + ",\n".join(lines) + """;

    public enum Physics { VANILLA, GROUND, GLIDE }

    public final String displayName, sport, rrModel, rrSound, fallbackShape;
    public final Physics physics;
    public final int wheelSlot, boostFuelTicks;
    public final float maxSpeed, pedalAccel, pedalTopSpeed, turnRate, slopeGain, friction, stepHeight, jumpBoost,
            glideLift, glideDive, glideClimb, glideDrag, boostAccel, fuelRegen;
    public final boolean canClimb;

    Gear(String displayName, String sport, Physics physics, int wheelSlot, float maxSpeed, float pedalAccel, float pedalTopSpeed, float turnRate,
         float slopeGain, float friction, boolean canClimb, float stepHeight, float jumpBoost, float glideLift, float glideDive,
         float glideClimb, float glideDrag, float boostAccel, int boostFuelTicks, float fuelRegen,
         String rrModel, String rrSound, String fallbackShape) {
        this.displayName = displayName; this.sport = sport; this.physics = physics; this.wheelSlot = wheelSlot;
        this.maxSpeed = maxSpeed; this.pedalAccel = pedalAccel; this.pedalTopSpeed = pedalTopSpeed; this.turnRate = turnRate; this.slopeGain = slopeGain;
        this.friction = friction; this.canClimb = canClimb; this.stepHeight = stepHeight; this.jumpBoost = jumpBoost;
        this.glideLift = glideLift; this.glideDive = glideDive; this.glideClimb = glideClimb; this.glideDrag = glideDrag;
        this.boostAccel = boostAccel; this.boostFuelTicks = boostFuelTicks; this.fuelRegen = fuelRegen;
        this.rrModel = rrModel; this.rrSound = rrSound; this.fallbackShape = fallbackShape;
    }

    public boolean isSnow() { return sport.equals("ski") || sport.equals("snowboard"); }
    public boolean isBike() { return sport.equals("bike") || sport.equals("bmx"); }

    public static Gear byId(int ordinal) { Gear[] v = values(); return ordinal >= 0 && ordinal < v.length ? v[ordinal] : ON_FOOT; }
}
""")

t = sheet("tricks")
lines = []
for r in t["rows"]:
    alts = ", ".join("new String[]{" + ", ".join(json.dumps(k) for k in a.split("+")) + "}" for a in r["input"].split("|")) if r["input"] != "none" else ""
    lines.append(f'    {r["id"].upper()}({j(r["name"])}, Kind.{r["kind"].upper()}, new String[]{{{", ".join(json.dumps(s) for s in r["sports"])}}}, '
                 f'new String[][]{{{alts}}}, {r["points"]}, {r["holdPointsPerTick"]}, {r["animTicks"]}, {j(r["rrCallout"].split("#")[1])})')
open(os.path.join(OUT, "Trick.java"), "w").write(HEAD.format("tricks") + """public enum Trick {
""" + ",\n".join(lines) + """;

    public enum Kind { FLIP, SPIN, GRAB, STYLE, ROLL, PROXIMITY, META }

    public final String displayName, calloutKey;
    public final Kind kind;
    public final String[] sports;
    /** Alternatives; each is a set of control ids held together. */
    public final String[][] inputs;
    public final int points, holdPointsPerTick, animTicks;

    Trick(String displayName, Kind kind, String[] sports, String[][] inputs, int points, int holdPointsPerTick, int animTicks, String calloutKey) {
        this.displayName = displayName; this.kind = kind; this.sports = sports; this.inputs = inputs;
        this.points = points; this.holdPointsPerTick = holdPointsPerTick; this.animTicks = animTicks; this.calloutKey = calloutKey;
    }

    public boolean forSport(String sport) { for (String s : sports) if (s.equals(sport)) return true; return false; }
}
""")

s = sheet("surfaces")
lines = [f'    {r["id"].upper()}({json.dumps(r["blockTag"])}, {float(r["bikeFrictionMul"])}f, {float(r["snowFrictionMul"])}f, {json.dumps(r["label"])})' for r in s["rows"]]
open(os.path.join(OUT, "Surface.java"), "w").write(HEAD.format("surfaces") + """public enum Surface {
""" + ",\n".join(lines) + """;

    public final String[] blocks;
    public final float bikeFrictionMul, snowFrictionMul;
    public final String label;

    Surface(String blocks, float bikeFrictionMul, float snowFrictionMul, String label) {
        this.blocks = blocks.split("\\\\|"); this.bikeFrictionMul = bikeFrictionMul; this.snowFrictionMul = snowFrictionMul; this.label = label;
    }

    public static Surface of(String blockId) {
        for (Surface s : values()) for (String b : s.blocks) if (b.equals(blockId)) return s;
        return DEFAULT;
    }
}
""")

c = sheet("controls")
lines = [f'    {r["id"].upper()}({json.dumps(r["label"])}, {json.dumps(r["key"])})' for r in c["rows"]]
open(os.path.join(OUT, "Control.java"), "w").write(HEAD.format("controls") + """public enum Control {
""" + ",\n".join(lines) + """;

    public final String label, key;

    Control(String label, String key) { this.label = label; this.key = key; }

    public boolean isVanilla() { return key.startsWith("vanilla:"); }

    public static Control byId(String id) { return valueOf(id.toUpperCase()); }
}
""")
print("generated Gear, Trick, Surface, Control")
